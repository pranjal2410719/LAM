"""Production-grade resilient HTTP client and relay for Qrie-LAM integration.

Handles:
- Connect (2.0s) and Read (5.0s) timeouts.
- Bounded retries for transient HTTP 502/503/504 and network errors.
- Exponential backoff with jitter.
- Replay and deduplication handling for offline ledger outbox events.
- Strict conflict detection (HTTP 409).
- Safe fallback recommendation selection when LAM is unavailable without
  fabricating mastery or simulating BKT parameter updates.
"""

import asyncio
import logging
import random
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Any

import httpx

logger = logging.getLogger(__name__)

DEFAULT_CONNECT_TIMEOUT: float = 2.0
DEFAULT_READ_TIMEOUT: float = 5.0
DEFAULT_MAX_RETRIES: int = 3
DEFAULT_INITIAL_BACKOFF: float = 0.1
DEFAULT_BACKOFF_FACTOR: float = 2.0
RETRYABLE_STATUS_CODES: frozenset[int] = frozenset({502, 503, 504})


class LamClientError(Exception):
    """Base exception for all LAM client operations."""


class LamTimeoutError(LamClientError):
    """Raised when connection or read timeout budget is exhausted."""


class LamServiceUnavailableError(LamClientError):
    """Raised when LAM returns 502/503/504 after retries are exhausted."""


class LamConflictError(LamClientError):
    """Raised when an event ID is submitted with conflicting attributes (HTTP 409)."""


class LamAuthenticationError(LamClientError):
    """Raised when request is unauthorized or tenant mismatch occurs (HTTP 401/403)."""


class LamValidationError(LamClientError):
    """Raised when payload fails schema validation (HTTP 422)."""


@dataclass(frozen=True)
class IngestionResult:
    """Outcome of an event ingestion request."""

    status: str  # "ingested" or "duplicate"
    event_id: str
    tenant_id: str
    student_id: str
    affected_concept_ids: list[str]
    ingested_at: datetime
    message: str


@dataclass(frozen=True)
class RecommendationResult:
    """Recommendation decision returned by LAM or generated by safe fallback."""

    action_type: str
    target_concept_id: str
    assistance_level: int
    priority_tier: str
    reason_code: str
    suggested_strategy: str
    rationale: str
    policy_version: str
    safe_fallback: bool
    uncertainty: float | None = None
    concept_mastery: float | None = None
    relevant_learner_state_version: int | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class OutboxReplayReport:
    """Summary of an outbox drain and replay operation."""

    total_submitted: int
    ingested_count: int
    duplicate_count: int
    conflict_count: int
    failed_count: int
    errors: list[str] = field(default_factory=list)


class LamRelayClient:
    """Resilient client for dispatching Qrie events and retrieving recommendations from LAM."""

    def __init__(
        self,
        base_url: str,
        auth_token: str | None = None,
        tenant_id: str = "default_tenant",
        connect_timeout: float = DEFAULT_CONNECT_TIMEOUT,
        read_timeout: float = DEFAULT_READ_TIMEOUT,
        max_retries: int = DEFAULT_MAX_RETRIES,
        initial_backoff: float = DEFAULT_INITIAL_BACKOFF,
        backoff_factor: float = DEFAULT_BACKOFF_FACTOR,
        http_client: httpx.AsyncClient | None = None,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.auth_token = auth_token
        self.tenant_id = tenant_id
        self.timeout = httpx.Timeout(read_timeout, connect=connect_timeout)
        self.max_retries = max_retries
        self.initial_backoff = initial_backoff
        self.backoff_factor = backoff_factor
        self._external_client = http_client

    def _headers(self) -> dict[str, str]:
        headers = {
            "Content-Type": "application/json",
            "X-Tenant-ID": self.tenant_id,
        }
        if self.auth_token:
            headers["Authorization"] = f"Bearer {self.auth_token}"
        return headers

    async def _send_with_retry(
        self,
        method: str,
        path: str,
        json_body: dict[str, Any] | None = None,
    ) -> httpx.Response:
        """Executes HTTP request with bounded retries on transient errors and timeouts."""
        url = f"{self.base_url}{path}"
        headers = self._headers()
        backoff = self.initial_backoff

        client = self._external_client or httpx.AsyncClient(timeout=self.timeout)
        should_close = self._external_client is None

        try:
            for attempt in range(1, self.max_retries + 1):
                try:
                    resp = await client.request(
                        method=method,
                        url=url,
                        json=json_body,
                        headers=headers,
                        timeout=self.timeout,
                    )

                    # Non-retryable 4xx client errors
                    if resp.status_code == 409:
                        raise LamConflictError(f"HTTP 409 Conflict: {resp.text}")
                    if resp.status_code in (401, 403):
                        raise LamAuthenticationError(
                            f"HTTP {resp.status_code} Auth Error: {resp.text}"
                        )
                    if resp.status_code == 422:
                        raise LamValidationError(f"HTTP 422 Validation Error: {resp.text}")

                    # Retryable 5xx server errors
                    if resp.status_code in RETRYABLE_STATUS_CODES:
                        if attempt == self.max_retries:
                            raise LamServiceUnavailableError(
                                f"Service unavailable (HTTP {resp.status_code}) after "
                                f"{self.max_retries} attempts: {resp.text}"
                            )
                        jitter = random.uniform(0.8, 1.2)  # noqa: S311
                        sleep_time = backoff * jitter
                        logger.warning(
                            "Transient %d on attempt %d/%d; retrying in %.2fs",
                            resp.status_code,
                            attempt,
                            self.max_retries,
                            sleep_time,
                        )
                        await asyncio.sleep(sleep_time)
                        backoff *= self.backoff_factor
                        continue

                    # Any other HTTP error
                    resp.raise_for_status()
                    return resp

                except (httpx.ConnectTimeout, httpx.ReadTimeout, httpx.ConnectError) as exc:
                    if attempt == self.max_retries:
                        raise LamTimeoutError(
                            f"Connection to LAM timed out or refused after "
                            f"{self.max_retries} attempts: {exc}"
                        ) from exc
                    jitter = random.uniform(0.8, 1.2)  # noqa: S311
                    sleep_time = backoff * jitter
                    logger.warning(
                        "Network error (%s) on attempt %d/%d; retrying in %.2fs",
                        type(exc).__name__,
                        attempt,
                        self.max_retries,
                        sleep_time,
                    )
                    await asyncio.sleep(sleep_time)
                    backoff *= self.backoff_factor

            raise LamServiceUnavailableError("Max retries exceeded without response")
        finally:
            if should_close:
                await client.aclose()

    async def ingest_event(self, event_payload: dict[str, Any]) -> IngestionResult:
        """Submits learning event to LAM with idempotency and duplicate handling."""
        resp = await self._send_with_retry("POST", "/v1/events", json_body=event_payload)
        data = resp.json()
        raw_ingested_at = data.get("ingested_at")
        ingested_at = (
            datetime.fromisoformat(raw_ingested_at) if raw_ingested_at else datetime.now(UTC)
        )
        return IngestionResult(
            status=data.get("status", "ingested"),
            event_id=data.get("event_id", event_payload.get("event_id", "")),
            tenant_id=data.get("tenant_id", self.tenant_id),
            student_id=data.get("student_id", event_payload.get("student_id", "")),
            affected_concept_ids=data.get("affected_concept_ids", []),
            ingested_at=ingested_at,
            message=data.get("message", "Event processed successfully"),
        )

    async def get_recommendation(
        self,
        student_id: str,
        concept_id: str,
        consecutive_failures: int = 0,
        active_misconception_id: str | None = None,
        misconception_status: str | None = None,
        prerequisite_readiness: bool = True,
        prerequisite_concept_id: str | None = None,
        context_metadata: dict[str, Any] | None = None,
    ) -> RecommendationResult:
        """Requests next action recommendation, with safe fallback on service failure."""
        body: dict[str, Any] = {
            "student_id": student_id,
            "concept_id": concept_id,
            "consecutive_failures": consecutive_failures,
            "prerequisite_readiness": prerequisite_readiness,
        }
        if active_misconception_id is not None:
            body["active_misconception_id"] = active_misconception_id
        if misconception_status is not None:
            body["misconception_status"] = misconception_status
        if prerequisite_concept_id is not None:
            body["prerequisite_concept_id"] = prerequisite_concept_id
        if context_metadata is not None:
            body["context_metadata"] = context_metadata

        try:
            resp = await self._send_with_retry("POST", "/v1/recommendations", json_body=body)
            data = resp.json()
            return RecommendationResult(
                action_type=data["action_type"],
                target_concept_id=data["target_concept_id"],
                assistance_level=data["assistance_level"],
                priority_tier=data["priority_tier"],
                reason_code=data["reason_code"],
                suggested_strategy=data["suggested_strategy"],
                rationale=data["rationale"],
                policy_version=data["policy_version"],
                safe_fallback=data.get("safe_fallback", False),
                uncertainty=data.get("uncertainty"),
                concept_mastery=data.get("concept_mastery"),
                relevant_learner_state_version=data.get("relevant_learner_state_version"),
                metadata=data.get("metadata", {}),
            )
        except (LamTimeoutError, LamServiceUnavailableError) as err:
            logger.error("LAM unavailable for recommendation (%s); activating safe fallback", err)
            return self.safe_fallback_recommendation(
                target_concept_id=concept_id,
                reason="lam_service_unreachable_safe_fallback",
            )

    @staticmethod
    def safe_fallback_recommendation(
        target_concept_id: str,
        reason: str = "service_offline_safe_fallback",
    ) -> RecommendationResult:
        """Generates a safe fallback recommendation without fabricating mastery.

        Invariant: Never produces fabricated concept_mastery, uncertainty, or BKT parameters.
        """
        return RecommendationResult(
            action_type="diagnostic_probe",
            target_concept_id=target_concept_id,
            assistance_level=2,
            priority_tier="tier_7_difficulty_fit_practice",
            reason_code=reason,
            suggested_strategy="Deliver standard baseline practice problem while offline.",
            rationale=(
                "LAM intelligence backend is currently unreachable. Delivering safe baseline "
                "practice probe without modifying or fabricating learner state."
            ),
            policy_version="fallback_v1",
            safe_fallback=True,
            uncertainty=None,  # Never fabricated!
            concept_mastery=None,  # Never fabricated!
            relevant_learner_state_version=None,
            metadata={"offline_fallback": True},
        )

    async def replay_outbox(
        self,
        outbox_events: list[dict[str, Any]],
    ) -> OutboxReplayReport:
        """Replays offline outbox events to LAM sequentially, guaranteeing zero duplicate drift."""
        ingested = 0
        duplicates = 0
        conflicts = 0
        failures = 0
        errors: list[str] = []

        for event in outbox_events:
            try:
                result = await self.ingest_event(event)
                if result.status == "duplicate":
                    duplicates += 1
                else:
                    ingested += 1
            except LamConflictError as exc:
                conflicts += 1
                errors.append(f"Conflict on event {event.get('event_id')}: {exc}")
            except LamClientError as exc:
                failures += 1
                errors.append(f"Failed to ingest event {event.get('event_id')}: {exc}")

        return OutboxReplayReport(
            total_submitted=len(outbox_events),
            ingested_count=ingested,
            duplicate_count=duplicates,
            conflict_count=conflicts,
            failed_count=failures,
            errors=errors,
        )
